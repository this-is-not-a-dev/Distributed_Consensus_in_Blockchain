import { Bot, Camera, ImageIcon, PencilRuler } from 'lucide-react';
import { Board, Chip, Txt, Wire, Wires, draw, pop, spring, useScene } from '../scene/kit';
import type { SlideDef } from './registry';

const CYCLE = [
  { t: 'Evaporation', x: 90, y: 200 },
  { t: 'Condensation', x: 360, y: 200 },
  { t: 'Precipitation', x: 360, y: 430 },
  { t: 'Collection', x: 90, y: 430 },
];
const SHELVES = ['Unsplash (if key)', 'Openverse', 'Wikimedia'];
const PHOTOS = [
  ['linear-gradient(135deg,#6b4a2b,#c49a6c 60%,#3d2a18)', 'Photo by A. Rao · Openverse · CC BY'],
  ['linear-gradient(135deg,#2f4858,#8aa1a8 55%,#1b2a33)', 'Wikimedia Commons · CC BY-SA'],
  ['linear-gradient(135deg,#5c3d5e,#c08497 60%,#2e1d30)', 'Photo by K. Singh · Openverse · CC0'],
];

function Scene({ step }: { step: number }) {
  const root = useScene(step, (tl, next, q) => {
    pop(tl, q, '.divider, .side-l', 0, 0.1);
    pop(tl, q, '.q-l', 0.3);
    pop(tl, q, '.node', 0.7, 0.2);
    draw(tl, q, '.cyc', 1, 0.25);
    pop(tl, q, '.note-l', 2);
    next((at) => {
      pop(tl, q, '.side-r, .q-r', at, 0.1);
      q('.shelf').forEach((el, i) => tl.fromTo(el, { autoAlpha: 0 }, { autoAlpha: 1, borderColor: '#4cb6e8', duration: 0.3 }, at + 0.4 + i * 0.3));
      q('.photo').forEach((el, i) => tl.fromTo(el, { autoAlpha: 0, y: -60, rotate: -6 + i * 6 }, { autoAlpha: 1, y: 0, rotate: 0, ease: 'back.out(1.6)' }, at + 1.3 + i * 0.2));
      pop(tl, q, '.bot', at + 2);
      spring(tl, q, '.block', at + 2.5);
      tl.to(q('.bot'), { x: 40, autoAlpha: 0.3, duration: 0.4 }, at + 2.6);
    });
  });

  return (
    <Board root={root} step={step}>
      <div className="divider" style={{ left: 639, top: 30, width: 2, height: 660, background: 'linear-gradient(var(--line), transparent)' }} />
      <Txt x={40} y={30} className="side-l k-cap"><PencilRuler size={14} style={{ verticalAlign: -2 }} /> How does it work? → draw it</Txt>
      <Txt x={680} y={30} className="side-r k-cap"><Camera size={14} style={{ verticalAlign: -2 }} /> What does it look like? → find it</Txt>
      <Chip x={40} y={70} tone="sky" className="q-l">“How does the water cycle work?”</Chip>
      <Chip x={680} y={70} tone="gold" className="q-r">“What does a handloom look like?”</Chip>

      {CYCLE.map((c) => (
        <div key={c.t} className="node k-card" data-tone="sky" style={{ left: c.x, top: c.y, width: 190, height: 64, display: 'grid', placeItems: 'center', fontWeight: 600 }}>{c.t}</div>
      ))}
      <Wires>
        <Wire d="M 284 232 L 354 232" tone="sky" className="cyc" />
        <Wire d="M 455 268 L 455 424" tone="sky" className="cyc" />
        <Wire d="M 356 462 L 286 462" tone="sky" className="cyc" />
        <Wire d="M 185 426 L 185 270" tone="sky" className="cyc" />
      </Wires>
      <Txt x={40} y={560} w={560} className="note-l k-muted" style={{ fontSize: 15 }}>
        Drawn by code from a <span className="mono" style={{ color: 'var(--gold)' }}>meraki:visual</span> spec: chart, flowchart, diagram or table. Nothing is AI-generated.
      </Txt>

      {SHELVES.map((s, i) => (
        <span key={s} className="shelf k-chip" data-tone="sky" style={{ left: 680 + i * 190, top: 140, height: 36 }}>{i + 1}. {s}</span>
      ))}
      {PHOTOS.map(([bg, credit], i) => (
        <div key={i} className="photo" style={{ left: 680 + i * 190, top: 210, width: 175, height: 210, borderRadius: 12, background: bg, overflow: 'hidden', border: '1px solid var(--line-2)' }}>
          <ImageIcon size={34} color="rgba(255,255,255,0.5)" style={{ position: 'absolute', left: 70, top: 70 }} />
          <span style={{ position: 'absolute', left: 0, right: 0, bottom: 0, padding: '6px 8px', fontSize: 11, lineHeight: 1.3, background: 'rgba(0,0,0,0.7)', color: '#ddd' }}>{credit}</span>
        </div>
      ))}
      <span className="bot k-chip" data-tone="muted" style={{ left: 720, top: 470, height: 44, fontSize: 16 }}><Bot size={18} /> AI-generated image</span>
      <span className="block k-stamp" data-tone="red" style={{ left: 980, top: 466 }}>✗ BLOCKED</span>
      <Txt x={680} y={560} w={560} className="side-r k-muted" style={{ fontSize: 15 }}>
        Real, licensed photos with the photographer's credit. The search uses the concept being taught, not the learner's raw words.
      </Txt>
    </Board>
  );
}

export const slide: SlideDef = {
  Scene,
  steps: [
    {
      title: 'Concepts get drawn',
      caption: 'A process or structure question gets a diagram drawn in code: here, the water cycle as a looping flowchart.',
      say: "ShipLabs has two systems for pictures, and it never mixes them up. If the question is how does it work, like the water cycle, it draws a diagram in code. A flowchart, a chart or a table. Nothing is generated by AI.",
      body: <p className="r-p">Processes, structures and comparisons become a <code>meraki:visual</code> spec that <code>PathshalaVisual</code> renders as a chart, flowchart, diagram or table. If the text promises a diagram that never arrived, an honest note is added.</p>,
    },
    {
      title: 'Real things get real photos',
      caption: 'Appearance questions fetch credited photos from Unsplash, Openverse and Wikimedia; AI-generated images are never used.',
      say: "If the question is what does it look like, like a handloom, it finds real photos from free, licensed sources, with the photographer's credit. We never generate images with AI for teaching, because they can be wrong or misleading.",
      body: (
        <>
          <p className="r-p">Unsplash (only if a key is set) → Openverse → Wikimedia. Up to 6 groups × 6 photos, 8 s timeout each, attribution on every item.</p>
          <p className="r-note">Image API keys stay on the server. Only URLs and credits reach the browser.</p>
        </>
      ),
    },
  ],
};
